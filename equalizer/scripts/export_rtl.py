"""Export a quantized IntegerModel to RTL artifacts.

Writes rtl/gen/<name>/:
  cnn_eq_pkg.sv   shape, widths, N_PARAM and per-layer parameter offsets
  params.mem      parameter memory image, one 32-bit hex word per line
  tb_cfg.svh      test-bench constants (frames, lengths)
  test_in.mem     input sample codes (B_IN-bit two's complement, 2 hex digits per line)
  test_out.mem    expected outputs: z saturated to int16 (4 hex digits per line)
  meta.json       widths, worst-case accumulator bounds, test-frame BER

Usage:
    python scripts/export_rtl.py --model results/quant/ours_bce_w6/integer_model.pkl --name ours_bce_w6
"""
import argparse
import json
import pickle
from pathlib import Path

import numpy as np

from eqsim.data import load_dataset

DATA = Path("checkpoints/fp32_v1/imdd_data/test_fresh.npz")


def layer_shapes(im):
    return [(W.shape[0], W.shape[1]) for W in im.W]  # (oc, ic)


def worst_case_bits(im):
    """Signed width that holds |acc + bias| for any input, per layer."""
    bits = []
    for i, (W, b) in enumerate(zip(im.W, im.bias)):
        max_in = 2 ** (im.in_bits - 1) - 1 if i == 0 else 2 ** im.a_bits - 1
        bound = int(np.max(np.abs(W).reshape(W.shape[0], -1).sum(1) * max_in + np.abs(b)))
        bits.append(int(np.ceil(np.log2(bound + 1))) + 1)
    return bits


def build_param_image(im):
    words, offs = [], {"W": [], "B": [], "M": [], "S": []}
    L = len(im.W)
    for i in range(L):
        offs["W"].append(len(words))
        words += [int(v) for v in im.W[i].reshape(-1)]          # ((oc*IC + ic)*K + k)
        offs["B"].append(len(words))
        words += [int(v) for v in im.bias[i]]
        if i < L - 1:
            offs["M"].append(len(words))
            words += [int(v) for v in im.M[i]]
            offs["S"].append(len(words))
            words += [int(v) for v in im.S[i]]
        else:
            offs["M"].append(0)
            offs["S"].append(0)
    fb = getattr(im, "fb", None)
    offs["FB"] = len(words)
    if fb is not None:
        words += [int(v) for v in fb.reshape(-1)]             # (v * N_FB + k)
    return [w & 0xFFFF_FFFF for w in words], offs


def sv_array(vals):
    return "'{" + ", ".join(str(v) for v in vals) + "}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", type=Path, required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--frames", type=int, default=3)
    ap.add_argument("--frame-symbols", type=int, default=1024)
    ap.add_argument("--out", type=Path, default=Path("rtl/gen"))
    args = ap.parse_args()
    with open(args.model, "rb") as f:
        im = pickle.load(f)
    L, K, vp, nos = len(im.W), im.K, im.vp, im.nos
    C = im.W[0].shape[0]
    assert args.frame_symbols % vp == 0, "frame length must be a multiple of VP"
    assert all(oc == C for oc, _ in layer_shapes(im)[:-1]) and im.W[-1].shape[0] == vp

    wc = worst_case_bits(im)
    fb = getattr(im, "fb", None)
    n_fb = 0 if fb is None else fb.shape[1]
    acc_w = max(16, max(wc))
    if fb is not None:  # taps are stored in ACC_W bits; u = z + sum fb needs ACC_W + N_FB bits (dfe_stream UW)
        acc_w = max(acc_w, int(np.abs(fb).max()).bit_length() + 1)
    words, offs = build_param_image(im)
    assert all(int(v).bit_length() < acc_w for b in im.bias for v in np.abs(b))
    assert all(np.all((m > 0) & (m < 2 ** 16)) for m in im.M) and all(np.all((s >= 1) & (s <= 40)) for s in im.S)

    d = args.out / args.name
    d.mkdir(parents=True, exist_ok=True)
    pkg = f"""// Generated by scripts/export_rtl.py from {args.model.as_posix()} - do not edit.
package cnn_eq_pkg;
    localparam int L       = {L};
    localparam int K       = {K};
    localparam int C       = {C};
    localparam int VP      = {vp};
    localparam int NOS     = {nos};
    localparam int B_IN    = {im.in_bits};
    localparam int B_W     = {im.w_bits};
    localparam int B_A     = {im.a_bits};
    localparam int ACC_W   = {acc_w};
    localparam int N_PARAM = {len(words)};
    localparam int STRIDE_L [L] = {sv_array(im.strides)};
    localparam int W_OFF [L]    = {sv_array(offs['W'])};
    localparam int B_OFF [L]    = {sv_array(offs['B'])};
    localparam int M_OFF [L]    = {sv_array(offs['M'])};
    localparam int S_OFF [L]    = {sv_array(offs['S'])};
    localparam int N_FB    = {n_fb};        // decision-feedback taps (0 = none)
    localparam int FB_OFF  = {offs['FB']};
endpackage
"""
    (d / "cnn_eq_pkg.sv").write_text(pkg)
    (d / "params.mem").write_text("\n".join(f"{w:08x}" for w in words) + "\n")

    ds = load_dataset(DATA, 2, 2)
    rx, idx = ds.rx[0], ds.idx[0]
    n_s = args.frame_symbols
    ins, outs, errs = [], [], 0
    for fr in range(args.frames):
        seg = rx[fr * n_s * nos:(fr + 1) * n_s * nos].astype(np.float64)
        xq = im.quantize_input(seg)
        bits, z = im.forward_int(xq)
        ins += [int(v) & (2 ** im.in_bits - 1) for v in xq]
        outs += [int(np.clip(v, -32768, 32767)) & 0xFFFF for v in z]
        errs += int(np.sum(bits[32:-32] != idx[fr * n_s:(fr + 1) * n_s][32:-32]))
    (d / "test_in.mem").write_text("\n".join(f"{v:02x}" for v in ins) + "\n")
    (d / "test_out.mem").write_text("\n".join(f"{v:04x}" for v in outs) + "\n")
    (d / "tb_cfg.svh").write_text(
        f"// Generated by scripts/export_rtl.py - do not edit.\n"
        f"localparam int TB_FRAMES = {args.frames};\n"
        f"localparam int TB_FRAME_SYM = {n_s};\n"
        f"localparam int TB_FRAME_SAMPLES = {n_s * nos};\n")
    meta = {"name": args.name, "source": str(args.model), "L": L, "K": K, "C": C, "VP": vp, "NOS": nos,
            "B_IN": im.in_bits, "B_W": im.w_bits, "B_A": im.a_bits, "ACC_W": acc_w, "worst_case_acc_bits": wc,
            "N_PARAM": len(words), "offsets": offs, "N_FB": n_fb, "fb": None if fb is None else fb.tolist(),
            "s_in": im.s_in, "test_frames": args.frames,
            "frame_symbols": n_s, "test_bit_errors_excl_edges": errs,
            "test_bits_excl_edges": args.frames * (n_s - 64)}
    (d / "meta.json").write_text(json.dumps(meta, indent=2))
    print(json.dumps({k: meta[k] for k in ("name", "ACC_W", "worst_case_acc_bits", "N_PARAM", "test_bit_errors_excl_edges")}))


if __name__ == "__main__":
    main()
